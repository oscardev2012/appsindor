    public SeoRoute? Find(string path)
    {
        var p = Normalize(path);
        return Routes.FirstOrDefault(r => r.EnPath == p || r.EsPath == p);
    }

    public static string Normalize(string? path)
    {
        var value = (path ?? "/").Split('#')[0].Split('?')[0].TrimEnd('/');
        return string.IsNullOrEmpty(value) ? "/" : value;
    }

    public bool IsSpanish(string path)
    {
        var p = Normalize(path);
        return p == "/es" || p.StartsWith("/es/", StringComparison.Ordinal);
    }
