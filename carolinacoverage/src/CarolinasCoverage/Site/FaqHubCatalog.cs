    public static string RelatedPath(string relatedId, bool en)
    {
        if (relatedId is "index" or "home" or "")
        {
            return Lang.Home(en);
        }

        return SeoHubCatalog.TryGet(relatedId, out var hub) ? hub.Path(en) : Lang.Home(en);
    }

    public static string RelatedLabel(string relatedId, bool en)
    {
        if (relatedId is "index" or "home" or "")
        {
            return en ? "Home" : "Inicio";
        }

        return SeoHubCatalog.TryGet(relatedId, out var hub)
            ? (en ? hub.H1En : hub.H1Es)
            : (en ? "Home" : "Inicio");
    }

    public static IReadOnlyList<FaqItem> ForSchema(bool en) =>
        All.Select(item => new FaqItem(
            en ? item.QEn : item.QEs,
            (en ? item.FactEn : item.FactEs) + " " + (en ? item.WhyEn : item.WhyEs))).ToArray();
}
